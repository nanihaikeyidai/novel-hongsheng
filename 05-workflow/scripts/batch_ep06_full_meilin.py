def log(msg):
    line = time.strftime("[%H:%M:%S] ") + str(msg)
    print(line, flush=True)
    with LOG.open("a", encoding="utf-8") as f:
        f.write(line + "\n")


def prep_pascal():
    from PIL import Image
    if PASCAS.exists():
        return
    im = Image.open(PASCAS_SRC).convert("RGB")
    im.thumbnail((960, 960))
    im.save(PASCAS)
    log(f"帕斯卡参考图已生成 {PASCAS} {im.size}")


def main():
    for d in (SEGDIR, PROMPTDIR, CLIPDIR, ARCHIVEDIR, OUTDIR):
        d.mkdir(parents=True, exist_ok=True)
    prep_pascal()
    done = set(json.loads(PROGRESS.read_text(encoding="utf-8"))) if PROGRESS.exists() else []
    done = set(done)
    total = len(SEGMENTS)
    log(f"=== EP06 全本批量启动 | 共 {total} 段 | 已完成 {len(done)} 段 ===")

    for idx, s in enumerate(SEGMENTS, 1):
        sid = s["id"]
        dst = OUTDIR / f"EP06_{sid}_{s['scene']}_{s['name']}.mp4"
        if sid in done and dst.exists() and dst.stat().st_size > 100000:
            log(f"[{idx}/{total}] {sid} 已完成，跳过")
            continue
        pf = PROMPTDIR / f"梅林_{sid}_{s['scene']}_{s['name']}.txt"
        pf.write_text(s["prompt"].strip(), encoding="utf-8")
        n = len(s["prompt"].strip())
        if not (900 <= n <= 1450):
            log(f"[{idx}/{total}] {sid} 提示词 {n} 字符超出预算，仍继续")
        if s["p1"] == "pascal":
            args = ["--img1", str(GARAGE), "--img2", str(LANSUN), "--img3", str(PASCAS)]
        else:
            args = ["--img1", str(GARAGE), "--img2", str(LANSUN), "--img3", str(ANNA)]
        cmd = [str(PY), str(RUNNER), "--prompt", str(pf), *args,
               "--seconds", "15", "--template", "default",
               "--tag", f"ep06_full_{sid.lower()}", "--out", str(dst), "--no-sync"]
        log(f"[{idx}/{total}] {sid} {s['scene']} {s['name']} | {n} 字符 | 提交")
        t0 = time.time()
        r = subprocess.run(cmd, cwd=str(WF / "scripts"),
                           capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=1800)
        tail = "\n".join((r.stdout or "").strip().splitlines()[-6:])
        log(f"[{idx}/{total}] {sid} 返回 {r.returncode} 耗时 {(time.time()-t0)/60:.1f}min\n{tail}")
        if r.returncode != 0 or not dst.exists():
            log(f"[{idx}/{total}] {sid} 失败，保留现场，停止后续（可重跑本脚本续跑）")
            log((r.stderr or "")[-1500:])
            return 2
        shutil.copy2(dst, ARCHIVEDIR / dst.name)
        done.add(sid)
        PROGRESS.write_text(json.dumps(sorted(done), ensure_ascii=False), encoding="utf-8")
        log(f"[{idx}/{total}] {sid} 完成并归档 {dst.name}")

    DONE.write_text(f"全部 {total} 段完成 {time.strftime('%Y-%m-%d %H:%M:%S')}\n", encoding="utf-8")
    log(f"=== 全部 {total} 段生成完成 ===")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
