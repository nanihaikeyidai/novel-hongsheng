def write(seg_id: str, dirname: str, text: str, expect_audio: int) -> None:
    problems = lint(text, expect_audio)
    if problems:
        print(f"❌ 片段{seg_id} 门禁未通过:")
        for p in problems:
            print("   -", p)
        return
    d = EP / dirname
    d.mkdir(parents=True, exist_ok=True)
    (d / "动作流_H3纯提示词.txt").write_text(text, encoding="utf-8")
    print(f"✅ 片段{seg_id} {dirname}  {len(text)} 字  门禁通过")


